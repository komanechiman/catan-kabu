// 数字フォーマット
export function fmt(n) {
  n = Math.round(n || 0);
  return n.toLocaleString('ja-JP');
}
export function fmtG(n) {
  return fmt(n) + 'G';
}
export function pct(n, digits = 1) {
  const v = (n || 0) * 100;
  return (v > 0 ? '+' : '') + v.toFixed(digits) + '%';
}
